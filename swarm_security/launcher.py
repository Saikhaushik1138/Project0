"""Launch an isolated PX4/Gazebo experiment with a byte-preserving MAVLink relay."""

from __future__ import annotations

import argparse
import fcntl
import json
import math
import os
from pathlib import Path
import resource
import shutil
import signal
import socket
import subprocess
import sys
import time
import uuid


ROOT = Path(__file__).resolve().parents[1]
MAX_DRONES = 64


def positive_number(value: str) -> float:
    number = float(value)
    if not math.isfinite(number) or number <= 0:
        raise argparse.ArgumentTypeError("must be a finite positive number")
    return number


def drone_count(value: str) -> int:
    number = int(value)
    if not 1 <= number <= MAX_DRONES:
        raise argparse.ArgumentTypeError(f"must be between 1 and {MAX_DRONES}")
    return number


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(description=__doc__)
    result.add_argument("--drones", type=drone_count, default=1)
    result.add_argument("--security", choices=("baseline", "hmac", "chacha20"), default="baseline")
    result.add_argument("--keys", type=Path, help="per-vehicle keys generated by 'python -m swarm_security keygen'")
    result.add_argument("--headless", action="store_true", help="run the Gazebo server without its GUI")
    result.add_argument("--dry-run", action="store_true", help="print the plan without launching or writing files")
    result.add_argument("--duration", type=positive_number, help="seconds to run after all vehicles emit heartbeats")
    result.add_argument("--startup-timeout", type=positive_number, default=120.0)
    result.add_argument("--spacing", type=positive_number, default=3.0, help="grid spacing in metres")
    return result


def make_plan(args: argparse.Namespace) -> dict:
    columns = math.ceil(math.sqrt(args.drones))
    return {
        "security": args.security,
        "drones": args.drones,
        "headless": args.headless,
        "duration_seconds": args.duration,
        "px4_binary": str(ROOT / "build/px4_sitl_default/bin/px4"),
        "model": "gz_x500",
        "world": "default",
        "qgroundcontrol": "127.0.0.1:14550",
        "baseline_uses_transparent_relay": True,
        "vehicles": [
            {
                "instance": i,
                "system_id": i + 1,
                "pose": f"{(i % columns) * args.spacing:g},{(i // columns) * args.spacing:g},0,0,0,0",
                "px4_port": 18570 + i,
                "relay_ingress": 20000 + i,
                "qgc_reply_port": 21000 + i,
                "vehicle_tunnel_port": 22000 + i,
                "gcs_tunnel_port": 23000 + i,
            }
            for i in range(args.drones)
        ],
    }


def mavlink_startup() -> str:
    """One GCS link per vehicle; no API/camera/gimbal links bypass the relay."""
    return """#!/bin/sh
# Generated for this experiment. The source PX4 ROMFS is unchanged.
udp_gcs_port_local=$((18570+px4_instance))
udp_relay_port_remote=$((20000+px4_instance))
param set MAV_0_BROADCAST 0
mavlink start -x -u $udp_gcs_port_local -o $udp_relay_port_remote -t 127.0.0.1 -r 4000000
mavlink stream -r 50 -s POSITION_TARGET_LOCAL_NED -u $udp_gcs_port_local
mavlink stream -r 50 -s LOCAL_POSITION_NED -u $udp_gcs_port_local
mavlink stream -r 50 -s GLOBAL_POSITION_INT -u $udp_gcs_port_local
mavlink stream -r 50 -s ATTITUDE -u $udp_gcs_port_local
mavlink stream -r 50 -s ATTITUDE_QUATERNION -u $udp_gcs_port_local
mavlink stream -r 50 -s ATTITUDE_TARGET -u $udp_gcs_port_local
mavlink stream -r 50 -s SERVO_OUTPUT_RAW_0 -u $udp_gcs_port_local
mavlink stream -r 20 -s RC_CHANNELS -u $udp_gcs_port_local
mavlink stream -r 10 -s OPTICAL_FLOW_RAD -u $udp_gcs_port_local
"""


def prepare_romfs(run_dir: Path, root: Path = ROOT) -> Path:
    target = run_dir / "etc"
    shutil.copytree(root / "build/px4_sitl_default/etc", target)
    # Use current source startup scripts, while retaining generated build resources.
    for relative in ("init.d-posix/rcS", "init.d-posix/px4-rc.simulator",
                     "init.d-posix/airframes/4001_gz_x500"):
        shutil.copy2(root / "ROMFS/px4fmu_common" / relative, target / relative)
    (target / "init.d-posix/px4-rc.mavlink").write_text(mavlink_startup())
    return target


def check_ports(plan: dict) -> None:
    needed = 5 * len(plan["vehicles"]) + 64
    soft, hard = resource.getrlimit(resource.RLIMIT_NOFILE)
    if soft < needed:
        resource.setrlimit(resource.RLIMIT_NOFILE, (min(needed, hard), hard))
    sockets = []
    try:
        for vehicle in plan["vehicles"]:
            for field in ("px4_port", "relay_ingress", "qgc_reply_port", "vehicle_tunnel_port", "gcs_tunnel_port"):
                sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
                sockets.append(sock)
                try:
                    sock.bind(("127.0.0.1", vehicle[field]))
                except OSError as exc:
                    raise RuntimeError(f"UDP {vehicle[field]} is unavailable ({field}, instance {vehicle['instance']}): {exc}") from exc
    finally:
        for sock in sockets:
            sock.close()


def atomic_json(path: Path, data: dict) -> None:
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(data, indent=2) + "\n")
    temporary.replace(path)


def observed_systems(path: Path) -> set[int]:
    try:
        data = json.loads(path.read_text())
        if not isinstance(data, dict):
            return set()
        identities = data.get("heartbeat_system_ids", [])
        if not isinstance(identities, list) or any(
                not isinstance(value, int) or isinstance(value, bool)
                or not 1 <= value <= MAX_DRONES for value in identities):
            return set()
        return set(identities)
    except (OSError, ValueError, TypeError):
        return set()


class Processes:
    def __init__(self):
        self.items: list[tuple[str, subprocess.Popen, object]] = []

    def start(self, name: str, command: list[str], cwd: Path, env: dict, log: Path):
        handle = log.open("w")
        try:
            process = subprocess.Popen(command, cwd=cwd, env=env, stdout=handle,
                                       stderr=subprocess.STDOUT, start_new_session=True)
        except BaseException:
            handle.close()
            raise
        self.items.append((name, process, handle))
        return process

    def check(self):
        for name, process, handle in self.items:
            code = process.poll()
            if code is not None:
                raise RuntimeError(f"{name} exited with code {code}; see {handle.name}")

    def stop(self):
        # Every process owns a new session, including any children of the gz CLI.
        for sig, seconds in ((signal.SIGINT, 5), (signal.SIGTERM, 3), (signal.SIGKILL, 1)):
            for _, process, _ in reversed(self.items):
                try:
                    os.killpg(process.pid, sig)
                except ProcessLookupError:
                    pass
            deadline = time.monotonic() + seconds
            for _, process, _ in reversed(self.items):
                try:
                    process.wait(timeout=max(0.01, deadline - time.monotonic()))
                except subprocess.TimeoutExpired:
                    pass
        for _, _, handle in self.items:
            handle.close()


def wait_until(predicate, processes: Processes, timeout: float, description: str):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        processes.check()
        if predicate():
            return
        time.sleep(0.2)
    raise RuntimeError(f"Timed out waiting for {description}")


def world_ready(env: dict) -> bool:
    try:
        probe = subprocess.run(["gz", "service", "-l"], env=env,
                               capture_output=True, text=True, timeout=4)
        return probe.returncode == 0 and "/world/default/create" in probe.stdout.splitlines()
    except subprocess.TimeoutExpired:
        return False


def validate_runtime(args: argparse.Namespace, plan: dict):
    binary = Path(plan["px4_binary"])
    if not binary.is_file() or not os.access(binary, os.X_OK):
        raise RuntimeError("PX4 SITL binary missing. Build with: make px4_sitl_default")
    if not (binary.parent.parent / "etc/init.d-posix/rcS").is_file():
        raise RuntimeError("PX4 generated startup files missing. Build with: make px4_sitl_default")
    if not shutil.which("gz"):
        raise RuntimeError("Gazebo 'gz' is not in PATH. Install the Gazebo dependencies described in docs/setup.md.")
    if not (ROOT / "Tools/simulation/gz/models/x500/model.sdf").is_file():
        raise RuntimeError("Gazebo x500 assets missing. Initialize this checkout's simulation submodules.")
    if args.security != "baseline" and (args.keys is None or not args.keys.is_file()):
        raise RuntimeError("--keys must name an existing key file for hmac/chacha20")
    probe = subprocess.run([str(binary), "-h"], capture_output=True, text=True, timeout=10)
    if probe.returncode:
        raise RuntimeError("PX4 binary cannot execute: " + probe.stderr.strip())
    check_ports(plan)


def run(args: argparse.Namespace, plan: dict) -> int:
    validate_runtime(args, plan)
    runs = ROOT / "runs"
    runs.mkdir(exist_ok=True)
    with (runs / ".launcher.lock").open("a") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise RuntimeError("Another experiment launcher is running in this checkout") from exc
        run_id = time.strftime("%Y%m%d_%H%M%S") + "_" + uuid.uuid4().hex[:8]
        run_dir = runs / run_id
        run_dir.mkdir()
        print(f"Experiment output: {run_dir}", flush=True)
        etc = prepare_romfs(run_dir)
        manifest = dict(plan, status="starting", started_at=time.time(), run_id=run_id)
        manifest_path = run_dir / "manifest.json"
        atomic_json(manifest_path, manifest)
        env = os.environ.copy()
        env.update({
            "GZ_PARTITION": "uav_" + run_id,
            "PX4_GZ_STANDALONE": "1",
            "PX4_SYS_AUTOSTART": "4001",
            "PX4_SIM_MODEL": "gz_x500",
            "PX4_GZ_WORLD": "default",
            "PX4_GZ_MODEL_NAME": "",
            "PX4_GZ_MODELS": str(ROOT / "Tools/simulation/gz/models"),
            "PX4_GZ_WORLDS": str(ROOT / "Tools/simulation/gz/worlds"),
            "PYTHONPATH": str(ROOT) + os.pathsep + env.get("PYTHONPATH", ""),
        })
        env["GZ_SIM_RESOURCE_PATH"] = os.pathsep.join([
            env["PX4_GZ_MODELS"], env["PX4_GZ_WORLDS"], env.get("GZ_SIM_RESOURCE_PATH", "")])
        if args.headless:
            env["HEADLESS"] = "1"
        else:
            env.pop("HEADLESS", None)
        processes = Processes()
        ready = run_dir / "relay_ready.json"
        status = run_dir / "relay_status.json"
        relay = [sys.executable, "-m", "swarm_security.relay", "--drones", str(args.drones),
                 "--security", args.security, "--ready-file", str(ready),
                 "--status-file", str(status), "--metrics", str(run_dir / "relay_metrics.json")]
        if args.keys:
            relay += ["--keys", str(args.keys.resolve())]
        try:
            processes.start("MAVLink relay", relay, ROOT, env, run_dir / "relay.log")
            wait_until(ready.exists, processes, 15, "the relay to bind all sockets")
            world = str(ROOT / "Tools/simulation/gz/worlds/default.sdf")
            processes.start("Gazebo server", ["gz", "sim", "-r", "-s", "-v", "1", world],
                            run_dir, env, run_dir / "gazebo_server.log")
            wait_until(lambda: world_ready(env), processes, args.startup_timeout, "the Gazebo world service")
            if not args.headless:
                processes.start("Gazebo GUI", ["gz", "sim", "-g"], run_dir, env, run_dir / "gazebo_gui.log")
            for vehicle in plan["vehicles"]:
                instance = vehicle["instance"]
                work = run_dir / f"instance_{instance}"
                work.mkdir()
                instance_env = dict(env, PX4_GZ_MODEL_POSE=vehicle["pose"])
                processes.start(f"PX4 instance {instance}",
                                [plan["px4_binary"], "-i", str(instance), "-d", str(etc)],
                                work, instance_env, work / "px4.log")
                # Give each spawn a chance to enter Gazebo's service queue. Readiness is
                # always determined by observed heartbeats, never this interval.
                time.sleep(0.15)
            manifest["processes"] = [{"role": name, "pid": process.pid}
                                     for name, process, _ in processes.items]
            atomic_json(manifest_path, manifest)
            expected = {vehicle["system_id"] for vehicle in plan["vehicles"]}
            wait_until(lambda: expected <= observed_systems(status), processes,
                       max(args.startup_timeout, args.drones * 3), "heartbeats from every vehicle")
            manifest.update(status="ready", ready_at=time.time())
            atomic_json(manifest_path, manifest)
            print(f"Ready: heartbeats from {args.drones} vehicles (system IDs 1–{args.drones}). "
                  "Open QGroundControl with UDP 14550 enabled. Ctrl+C stops this experiment.", flush=True)
            deadline = time.monotonic() + args.duration if args.duration else float("inf")
            while time.monotonic() < deadline:
                processes.check()
                time.sleep(0.2)
            manifest["status"] = "completed"
            return 0
        except KeyboardInterrupt:
            manifest["status"] = "stopped"
            return 130
        except BaseException as exc:
            manifest.update(status="failed", error=str(exc))
            raise
        finally:
            processes.stop()
            manifest["processes"] = [{"role": name, "pid": process.pid,
                                       "exit_code": process.returncode}
                                      for name, process, _ in processes.items]
            manifest["stopped_at"] = time.time()
            atomic_json(manifest_path, manifest)


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    plan = make_plan(args)
    if args.dry_run:
        print(json.dumps(plan, indent=2))
        return 0
    previous = signal.getsignal(signal.SIGTERM)
    def interrupted(*_):
        raise KeyboardInterrupt
    signal.signal(signal.SIGTERM, interrupted)
    try:
        return run(args, plan)
    except (RuntimeError, OSError, subprocess.SubprocessError) as exc:
        print(f"Launch failed: {exc}", file=sys.stderr)
        return 1
    finally:
        signal.signal(signal.SIGTERM, previous)


if __name__ == "__main__":
    raise SystemExit(main())
